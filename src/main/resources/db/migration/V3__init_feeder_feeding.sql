-- =====================================================================
-- V3：喂养员（实名资料 / 认证申请）与喂养请求（信息模式，无资金）
-- =====================================================================

CREATE TABLE t_feeder_profile (
    id                BIGINT       NOT NULL COMMENT '喂养员资料ID（雪花）',
    user_id           BIGINT       NOT NULL COMMENT '用户ID',
    real_name_enc     VARCHAR(255) NOT NULL COMMENT '真实姓名密文',
    id_card_enc       VARCHAR(255) NOT NULL COMMENT '身份证号密文',
    id_card_hmac      VARCHAR(64)  NOT NULL COMMENT '身份证HMAC',
    phone_enc         VARCHAR(255) NOT NULL COMMENT '联系电话密文',
    phone_hmac        VARCHAR(64)  NOT NULL COMMENT '联系电话HMAC',
    district          VARCHAR(32)  NOT NULL COMMENT '常驻区县',
    service_districts VARCHAR(512) NULL COMMENT '可服务区县JSON数组',
    service_intro     VARCHAR(500) NULL COMMENT '服务介绍 50-500 字',
    service_times     VARCHAR(1024) NULL COMMENT '可服务时段JSON（按周）',
    price_once        BIGINT       NULL COMMENT '单次参考价（分）',
    price_daily       BIGINT       NULL COMMENT '单日参考价（分）',
    deposit_accepted  TINYINT      NOT NULL DEFAULT 0 COMMENT '是否接受押金担保',
    status            VARCHAR(16)  NOT NULL DEFAULT 'ACTIVE' COMMENT 'ACTIVE/PAUSED/EXPIRED/BANNED',
    profile_complete  TINYINT      NOT NULL DEFAULT 0 COMMENT '三步任务是否完成，完成后才展示',
    cert_expire_time  DATETIME     NULL COMMENT '认证有效期（12个月）',
    connect_count     INT          NOT NULL DEFAULT 0 COMMENT '累计对接次数',
    last_active_time  DATETIME     NULL COMMENT '最近活跃时间',
    create_time       DATETIME     NOT NULL DEFAULT CURRENT_TIMESTAMP,
    update_time       DATETIME     NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
    create_by         BIGINT       NULL,
    update_by         BIGINT       NULL,
    is_deleted        TINYINT      NOT NULL DEFAULT 0,
    version           INT          NOT NULL DEFAULT 0,
    PRIMARY KEY (id),
    UNIQUE KEY uk_feeder_user (user_id),
    KEY idx_feeder_list (status, district, profile_complete)
) ENGINE = InnoDB DEFAULT CHARSET = utf8mb4 COMMENT ='喂养员资料表';

CREATE TABLE t_feeder_apply (
    id            BIGINT       NOT NULL COMMENT '认证申请ID（雪花）',
    user_id       BIGINT       NOT NULL COMMENT '申请用户',
    real_name_enc VARCHAR(255) NOT NULL COMMENT '真实姓名密文',
    id_card_enc   VARCHAR(255) NOT NULL COMMENT '身份证号密文',
    id_card_hmac  VARCHAR(64)  NOT NULL COMMENT '身份证HMAC',
    phone_enc     VARCHAR(255) NOT NULL COMMENT '联系电话密文',
    phone_hmac    VARCHAR(64)  NOT NULL COMMENT '联系电话HMAC',
    district      VARCHAR(32)  NOT NULL COMMENT '服务区县',
    materials     VARCHAR(2048) NULL COMMENT '人脸/手持证件等材料JSON',
    status        VARCHAR(16)  NOT NULL DEFAULT 'PENDING' COMMENT 'PENDING/APPROVED/REJECTED',
    reject_reason VARCHAR(255) NULL COMMENT '退回原因',
    audit_admin_id BIGINT      NULL COMMENT '审核人',
    audit_time    DATETIME     NULL COMMENT '审核时间',
    create_time   DATETIME     NOT NULL DEFAULT CURRENT_TIMESTAMP,
    update_time   DATETIME     NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
    create_by     BIGINT       NULL,
    update_by     BIGINT       NULL,
    is_deleted    TINYINT      NOT NULL DEFAULT 0,
    version       INT          NOT NULL DEFAULT 0,
    PRIMARY KEY (id),
    KEY idx_feeder_apply_status (status, create_time),
    KEY idx_feeder_apply_user (user_id)
) ENGINE = InnoDB DEFAULT CHARSET = utf8mb4 COMMENT ='喂养员认证申请表';

CREATE TABLE t_feeding_request (
    id             BIGINT       NOT NULL COMMENT '喂养请求ID（雪花）',
    user_id        BIGINT       NOT NULL COMMENT '发布用户',
    feeder_id      BIGINT       NULL COMMENT '定向喂养员用户ID，公开请求为空',
    pet_id         BIGINT       NOT NULL COMMENT '关联宠物档案',
    service_type   VARCHAR(16)  NOT NULL COMMENT 'ONCE单次/MULTI_DAY按日',
    start_time     DATETIME     NOT NULL COMMENT '开始时间',
    end_time       DATETIME     NULL COMMENT '结束时间（按日）',
    daily_time     VARCHAR(64)  NULL COMMENT '每日时段描述',
    district       VARCHAR(32)  NOT NULL COMMENT '区县（成都）',
    address_enc    VARCHAR(255) NOT NULL COMMENT '详细地址密文，对接成功后互见',
    contact_name   VARCHAR(32)  NOT NULL COMMENT '联系人姓名',
    contact_enc    VARCHAR(255) NOT NULL COMMENT '联系电话密文',
    contact_hmac   VARCHAR(64)  NOT NULL COMMENT '联系电话HMAC',
    pet_note       VARCHAR(200) NULL COMMENT '宠物情况补充',
    special_require VARCHAR(200) NULL COMMENT '特殊要求',
    status         VARCHAR(16)  NOT NULL DEFAULT 'PENDING' COMMENT 'PENDING/CONTACTED/COMPLETED/CLOSED',
    close_reason   VARCHAR(255) NULL COMMENT '关闭原因',
    contact_time   DATETIME     NULL COMMENT '标记已联系时间',
    complete_time  DATETIME     NULL COMMENT '完成时间',
    create_time    DATETIME     NOT NULL DEFAULT CURRENT_TIMESTAMP,
    update_time    DATETIME     NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
    create_by      BIGINT       NULL,
    update_by      BIGINT       NULL,
    is_deleted     TINYINT      NOT NULL DEFAULT 0,
    version        INT          NOT NULL DEFAULT 0,
    PRIMARY KEY (id),
    KEY idx_feeding_user (user_id, status),
    KEY idx_feeding_feeder (feeder_id, status),
    KEY idx_feeding_status (status, create_time)
) ENGINE = InnoDB DEFAULT CHARSET = utf8mb4 COMMENT ='喂养请求表（信息模式，无资金）';
