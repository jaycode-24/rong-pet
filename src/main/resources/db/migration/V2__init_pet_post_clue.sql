-- =====================================================================
-- V2：宠物档案 / 帖子（寻宠·招领·相亲）/ 线索 / 认领申请 / 帖子操作日志
-- 约定：金额一律 bigint 存分；状态枚举值见各列注释；图片 JSON 数组存文本
-- =====================================================================

CREATE TABLE t_pet (
    id              BIGINT       NOT NULL COMMENT '宠物ID（雪花）',
    user_id         BIGINT       NOT NULL COMMENT '归属用户',
    name            VARCHAR(10)  NOT NULL COMMENT '宠物名字',
    pet_type        VARCHAR(16)  NOT NULL COMMENT 'CAT/DOG/EXOTIC',
    breed           VARCHAR(32)  NOT NULL COMMENT '品种',
    gender          VARCHAR(16)  NOT NULL DEFAULT 'UNKNOWN' COMMENT 'MALE/FEMALE/UNKNOWN',
    birth_date      DATE         NULL COMMENT '出生日期',
    weight          DECIMAL(5,1) NULL COMMENT '体重（千克）',
    sterilized      VARCHAR(16)  NOT NULL DEFAULT 'UNKNOWN' COMMENT 'YES/NO/UNKNOWN',
    vaccine_status  VARCHAR(16)  NULL COMMENT 'DONE/PARTIAL/NONE',
    chip_feature    VARCHAR(64)  NULL COMMENT '芯片或项圈特征',
    avatar_url      VARCHAR(512) NOT NULL COMMENT '头像（必填1张）',
    photos          VARCHAR(2048) NULL COMMENT '照片JSON数组，最多6张',
    remark          VARCHAR(500) NULL COMMENT '备注',
    create_time     DATETIME     NOT NULL DEFAULT CURRENT_TIMESTAMP,
    update_time     DATETIME     NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
    create_by       BIGINT       NULL,
    update_by       BIGINT       NULL,
    is_deleted      TINYINT      NOT NULL DEFAULT 0,
    version         INT          NOT NULL DEFAULT 0,
    PRIMARY KEY (id),
    KEY idx_pet_user (user_id, is_deleted)
) ENGINE = InnoDB DEFAULT CHARSET = utf8mb4 COMMENT ='宠物档案表';

CREATE TABLE t_post (
    id                BIGINT       NOT NULL COMMENT '帖子ID（雪花）',
    type              VARCHAR(16)  NOT NULL COMMENT 'LOST寻宠/FOUND招领/BREED相亲',
    user_id           BIGINT       NOT NULL COMMENT '发布者',
    pet_id            BIGINT       NULL COMMENT '关联宠物档案，可空',
    pet_snapshot      VARCHAR(4000) NULL COMMENT '发布时宠物字段快照JSON',
    pet_type          VARCHAR(16)  NOT NULL COMMENT 'CAT/DOG/EXOTIC',
    breed             VARCHAR(32)  NOT NULL COMMENT '品种',
    title             VARCHAR(64)  NOT NULL COMMENT '列表标题',
    gender            VARCHAR(16)  NULL COMMENT 'MALE/FEMALE/UNKNOWN',
    color             VARCHAR(32)  NULL COMMENT '毛色',
    size              VARCHAR(16)  NULL COMMENT 'SMALL/MEDIUM/LARGE',
    sterilized        VARCHAR(16)  NULL COMMENT 'YES/NO/UNKNOWN',
    chip_feature      VARCHAR(64)  NULL COMMENT '芯片或项圈特征',
    age               DECIMAL(4,1) NULL COMMENT '年龄（岁），相亲用',
    weight            DECIMAL(5,1) NULL COMMENT '体重（千克），相亲用',
    vaccine_status    VARCHAR(16)  NULL COMMENT 'DONE/PARTIAL/NONE',
    deworm_status     VARCHAR(16)  NULL COMMENT 'RECENT/NONE',
    genetic_screening VARCHAR(255) NULL COMMENT '遗传病筛查结论',
    breed_intent      VARCHAR(16)  NULL COMMENT 'PLAY交友/BREED繁育',
    expect_condition  VARCHAR(255) NULL COMMENT '期望条件',
    district          VARCHAR(32)  NOT NULL COMMENT '成都区县',
    location          VARCHAR(255) NOT NULL COMMENT '地点描述',
    location_lat_lng  VARCHAR(64)  NULL COMMENT '选点坐标 lat,lng',
    event_time        DATETIME     NOT NULL COMMENT '走失/捡拾/期望时间',
    contact_enc       VARCHAR(255) NOT NULL COMMENT '联系电话密文',
    contact_hmac      VARCHAR(64)  NOT NULL COMMENT '联系电话HMAC索引',
    description       VARCHAR(500) NOT NULL COMMENT '详细描述',
    images            VARCHAR(2048) NOT NULL COMMENT '图片JSON数组，1-9张',
    cover_url         VARCHAR(512) NOT NULL COMMENT '首图',
    reward_amount     BIGINT       NOT NULL DEFAULT 0 COMMENT '悬赏本金（分），0为无悬赏',
    reward_fee        BIGINT       NOT NULL DEFAULT 0 COMMENT '平台服务费（分）',
    reward_status     VARCHAR(16)  NOT NULL DEFAULT 'NONE' COMMENT 'NONE/FROZEN/SPLITTING/PAID/REFUNDING/REFUNDED',
    reward_days       INT          NULL COMMENT '悬赏有效期天数 7/15/30',
    reward_expire_time DATETIME    NULL COMMENT '悬赏到期时间',
    gratuity_amount   BIGINT       NOT NULL DEFAULT 0 COMMENT '感谢金金额（分），招领专用',
    status            VARCHAR(24)  NOT NULL COMMENT '见附录B帖子状态',
    reject_reason     VARCHAR(255) NULL COMMENT '驳回原因',
    audit_remark      VARCHAR(255) NULL COMMENT '审核备注',
    edit_count        INT          NOT NULL DEFAULT 0 COMMENT '编辑次数，上限1',
    top_type          VARCHAR(16)  NULL COMMENT 'PAID/FREE/MANUAL',
    top_expire_time   DATETIME     NULL COMMENT '置顶到期时间',
    expire_time       DATETIME     NULL COMMENT '帖子到期时间',
    extend_count      INT          NOT NULL DEFAULT 0 COMMENT '延长次数，上限1',
    found_time        DATETIME     NULL COMMENT '确认找回时间',
    found_note        VARCHAR(500) NULL COMMENT '找回经过简述',
    found_proof       VARCHAR(2048) NULL COMMENT '归还凭证图片JSON',
    view_count        INT          NOT NULL DEFAULT 0 COMMENT '浏览量',
    clue_count        INT          NOT NULL DEFAULT 0 COMMENT '线索数',
    claim_count       INT          NOT NULL DEFAULT 0 COMMENT '认领申请数',
    agreement_version VARCHAR(32)  NULL COMMENT '协议版本',
    create_time       DATETIME     NOT NULL DEFAULT CURRENT_TIMESTAMP,
    update_time       DATETIME     NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
    create_by         BIGINT       NULL,
    update_by         BIGINT       NULL,
    is_deleted        TINYINT      NOT NULL DEFAULT 0,
    version           INT          NOT NULL DEFAULT 0,
    PRIMARY KEY (id),
    KEY idx_post_list (type, status, district),
    KEY idx_post_reward (status, reward_amount),
    KEY idx_post_top (top_expire_time),
    KEY idx_post_user (user_id, status),
    KEY idx_post_expire (status, expire_time)
) ENGINE = InnoDB DEFAULT CHARSET = utf8mb4 COMMENT ='帖子表（寻宠/招领/相亲）';

CREATE TABLE t_clue (
    id            BIGINT       NOT NULL COMMENT '线索ID（雪花）',
    post_id       BIGINT       NOT NULL COMMENT '所属帖子',
    user_id       BIGINT       NOT NULL COMMENT '线索提交者',
    content       VARCHAR(500) NOT NULL COMMENT '线索描述',
    images        VARCHAR(2048) NULL COMMENT '图片JSON数组，可空',
    contact_enc   VARCHAR(255) NOT NULL COMMENT '联系方式密文',
    contact_hmac  VARCHAR(64)  NOT NULL COMMENT '联系方式HMAC',
    status        VARCHAR(16)  NOT NULL DEFAULT 'PENDING' COMMENT 'PENDING/VALID/INVALID/CHEATED',
    invalid_reason VARCHAR(255) NULL COMMENT '驳回/无效原因',
    score         TINYINT      NULL COMMENT '发布者评分1-5，未评为空',
    score_comment VARCHAR(100) NULL COMMENT '一句话评语',
    score_source  VARCHAR(16)  NULL COMMENT 'PUBLISHER/SYSTEM_DEFAULT',
    share_amount  BIGINT       NOT NULL DEFAULT 0 COMMENT '分得金额（分），转付后固化',
    pay_status    VARCHAR(16)  NOT NULL DEFAULT 'UNPAID' COMMENT 'UNPAID/PAID/FROZEN/FAILED',
    detail_public TINYINT      NOT NULL DEFAULT 0 COMMENT '当事人是否同意公开本人的评分与分账明细',
    create_time   DATETIME     NOT NULL DEFAULT CURRENT_TIMESTAMP,
    update_time   DATETIME     NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
    create_by     BIGINT       NULL,
    update_by     BIGINT       NULL,
    is_deleted    TINYINT      NOT NULL DEFAULT 0,
    version       INT          NOT NULL DEFAULT 0,
    PRIMARY KEY (id),
    KEY idx_clue_post (post_id, status),
    KEY idx_clue_user (post_id, user_id)
) ENGINE = InnoDB DEFAULT CHARSET = utf8mb4 COMMENT ='线索表';

CREATE TABLE t_claim (
    id            BIGINT       NOT NULL COMMENT '认领申请ID（雪花）',
    post_id       BIGINT       NOT NULL COMMENT '招领帖ID',
    user_id       BIGINT       NOT NULL COMMENT '申请人（疑似失主）',
    description   VARCHAR(300) NOT NULL COMMENT '主人特征、丢失经过 20-200 字',
    materials     VARCHAR(2048) NOT NULL COMMENT '证明材料JSON数组，至少2项',
    status        VARCHAR(16)  NOT NULL DEFAULT 'PENDING_AUDIT' COMMENT 'PENDING_AUDIT/APPROVED/REJECTED/CONFIRMED/REFUSED',
    audit_remark  VARCHAR(255) NULL COMMENT '审核/拒绝原因',
    confirm_time  DATETIME     NULL COMMENT '拾宠人确认时间',
    create_time   DATETIME     NOT NULL DEFAULT CURRENT_TIMESTAMP,
    update_time   DATETIME     NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
    create_by     BIGINT       NULL,
    update_by     BIGINT       NULL,
    is_deleted    TINYINT      NOT NULL DEFAULT 0,
    version       INT          NOT NULL DEFAULT 0,
    PRIMARY KEY (id),
    KEY idx_claim_post (post_id, status),
    KEY idx_claim_user (user_id)
) ENGINE = InnoDB DEFAULT CHARSET = utf8mb4 COMMENT ='招领认领申请表';

CREATE TABLE t_post_log (
    id            BIGINT       NOT NULL COMMENT '日志ID（雪花）',
    post_id       BIGINT       NOT NULL COMMENT '帖子ID',
    operator_id   BIGINT       NULL COMMENT '操作者ID',
    operator_type VARCHAR(16)  NOT NULL COMMENT 'USER/ADMIN/SYSTEM',
    action        VARCHAR(32)  NOT NULL COMMENT '操作类型',
    from_status   VARCHAR(24)  NULL COMMENT '变更前状态',
    to_status     VARCHAR(24)  NULL COMMENT '变更后状态',
    detail        VARCHAR(500) NULL COMMENT '说明',
    create_time   DATETIME     NOT NULL DEFAULT CURRENT_TIMESTAMP,
    PRIMARY KEY (id),
    KEY idx_post_log_post (post_id, create_time)
) ENGINE = InnoDB DEFAULT CHARSET = utf8mb4 COMMENT ='帖子操作日志（append-only）';
